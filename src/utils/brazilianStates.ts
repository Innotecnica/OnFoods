// Função para converter nome do estado para código
export function getStateCodeFromName(stateName: string): string | null {
  const normalizedStateName = stateName.toLowerCase().trim();
  
  const state = BRAZILIAN_STATES.find(s => 
    s.name.toLowerCase() === normalizedStateName ||
    s.code.toLowerCase() === normalizedStateName
  );
  
  return state ? state.code : null;
}

