
import { useState, useRef, useCallback } from "react";
import { supabase } from "@/integrations/supabase/client";
import { toast } from "@/hooks/use-toast";
import i18n from "@/i18n";
import { validateAndFormatPhone } from "@/utils/phoneValidation";

interface WhatsAppConfig {
  whatsapp_phone: string;
  whatsapp_token: string;
  is_active: boolean;
}

interface SendResult {
  success: boolean;
  data?: unknown;
  error?: string;
}

interface WhatsAppHandlerResponse {
  success: boolean;
  error?: string;
  phoneNumber?: string;
  messageId?: string;
}

interface RateLimitState {
  count: number;
  resetTime: number;
}

export function useWhatsAppIntegration() {
  const [isSending, setIsSending] = useState(false);
  const configCache = useRef<Map<string, { config: WhatsAppConfig; timestamp: number }>>(new Map());
  const rateLimitRef = useRef<Map<string, RateLimitState>>(new Map());
  
  // Cache timeout: 5 minutes
  const CACHE_TIMEOUT = 5 * 60 * 1000;
  // Rate limit: 10 messages per minute per establishment
  const RATE_LIMIT = 10;
  const RATE_WINDOW = 60 * 1000;

  // Validate phone number with proper formatting
  const validatePhone = useCallback((phone: string): { isValid: boolean; formatted?: string; error?: string } => {
    if (!phone || typeof phone !== 'string') {
      return { isValid: false, error: 'Número de telefone é obrigatório' };
    }

    const validation = validateAndFormatPhone(phone.trim());
    if (!validation.isValid) {
      return { isValid: false, error: validation.error };
    }

    return { 
      isValid: true, 
      formatted: validation.international.replace(/\D/g, '') // WhatsApp format
    };
  }, []);

  // Check rate limit for establishment
  const checkRateLimit = useCallback((establishmentId?: string): boolean => {
    const key = establishmentId || 'global';
    const now = Date.now();
    const current = rateLimitRef.current.get(key);

    if (!current || now > current.resetTime) {
      rateLimitRef.current.set(key, { count: 1, resetTime: now + RATE_WINDOW });
      return true;
    }

    if (current.count >= RATE_LIMIT) {
      return false;
    }

    current.count++;
    return true;
  }, [RATE_WINDOW]);

  // Get cached configuration or fetch from database
  const getConfig = useCallback(async (establishmentId?: string): Promise<WhatsAppConfig | null> => {
    if (!establishmentId) return null;

    const cacheKey = establishmentId;
    const cached = configCache.current.get(cacheKey);
    const now = Date.now();

    // Return cached config if still valid
    if (cached && (now - cached.timestamp) < CACHE_TIMEOUT) {
      return cached.config;
    }

    try {
      const { data, error } = await supabase
        .from('chatbot_configs')
        .select('whatsapp_phone, whatsapp_token, is_active')
        .eq('user_id', establishmentId)
        .eq('is_active', true)
        .single();

      if (error || !data) {
        configCache.current.delete(cacheKey);
        return null;
      }

      const config: WhatsAppConfig = {
        whatsapp_phone: data.whatsapp_phone,
        whatsapp_token: data.whatsapp_token,
        is_active: data.is_active
      };

      // Cache the configuration
      configCache.current.set(cacheKey, { config, timestamp: now });
      return config;

    } catch (error) {
      console.error('Error fetching WhatsApp config:', error);
      return null;
    }
  }, [CACHE_TIMEOUT]);

  // Retry logic with exponential backoff
  const retryWithBackoff = useCallback(async <T>(
    operation: () => Promise<T>,
    maxRetries: number = 3,
    baseDelay: number = 1000
  ): Promise<T> => {
    for (let attempt = 0; attempt <= maxRetries; attempt++) {
      try {
        return await operation();
      } catch (error) {
        if (attempt === maxRetries) {
          throw error;
        }

        const delay = baseDelay * Math.pow(2, attempt);
        console.log(`Retry attempt ${attempt + 1}/${maxRetries + 1} in ${delay}ms`);
        await new Promise(resolve => setTimeout(resolve, delay));
      }
    }
    throw new Error('Max retries exceeded');
  }, []);

  // Enviar pedido para estabelecimento via WhatsApp
  const sendOrderToWhatsApp = useCallback(async (orderId: string): Promise<SendResult> => {
    if (!orderId || typeof orderId !== 'string') {
      return { success: false, error: 'ID do pedido é obrigatório' };
    }

    try {
      setIsSending(true);

      const result = await retryWithBackoff<WhatsAppHandlerResponse>(async () => {
        const { data, error } = await supabase.functions.invoke('whatsapp-unified-handler', {
          body: { 
            orderId,
            messageType: 'order_summary',
            message: '' // Will be generated by the function
          }
        });

        if (error) {
          throw new Error(error.message);
        }

        return data;
      });

      if (result?.success) {
      toast({
        title: i18n.t('common:order_sent_whatsapp'),
        description: i18n.t('common:order_sent_establishment', { orderNumber: orderId.slice(-8) }),
      });
        
        return { success: true, data: result };
      }

      return { success: false, error: result?.error || 'Falha ao enviar pedido' };
    } catch (error) {
      console.error('Error sending WhatsApp order:', error);
      const errorMessage = error instanceof Error ? error.message : i18n.t('common:whatsapp_send_error');
      
      toast({
        title: i18n.t('common:order_send_error_title'),
        description: errorMessage,
        variant: "destructive",
      });
      
      return { success: false, error: errorMessage };
    } finally {
      setIsSending(false);
    }
  }, [retryWithBackoff]);

  // Enviar notificação de status do pedido para cliente
  const sendStatusUpdateToCustomer = useCallback(async (
    orderId: string, 
    status: string, 
    customerPhone: string
  ): Promise<SendResult> => {
    // Validate inputs
    if (!orderId || !status || !customerPhone) {
      return { success: false, error: 'Todos os parâmetros são obrigatórios' };
    }

    const phoneValidation = validatePhone(customerPhone);
    if (!phoneValidation.isValid) {
      return { success: false, error: phoneValidation.error };
    }

    try {
      setIsSending(true);

      const result = await retryWithBackoff<WhatsAppHandlerResponse>(async () => {
        const { data, error } = await supabase.functions.invoke('whatsapp-unified-handler', {
          body: { 
            to: phoneValidation.formatted,
            orderId,
            status,
            messageType: 'status_update',
            message: '' // Will be generated by the function
          }
        });

        if (error) {
          throw new Error(error.message);
        }

        return data;
      });

      if (result?.success) {
        toast({
          title: i18n.t('common:notification_sent_title'),
          description: i18n.t('common:notification_sent_desc'),
        });
        return { success: true, data: result };
      }

      return { success: false, error: result?.error || 'Falha ao enviar notificação' };
    } catch (error) {
      console.error('Error sending status update:', error);
      return { success: false, error: error instanceof Error ? error.message : 'Erro desconhecido' };
    } finally {
      setIsSending(false);
    }
  }, [validatePhone, retryWithBackoff]);

  // Enviar mensagem personalizada via WhatsApp
  const sendCustomMessage = useCallback(async (
    to: string, 
    message: string, 
    establishmentId?: string
  ): Promise<SendResult> => {
    // Validate inputs
    if (!to || !message) {
      return { success: false, error: 'Destinatário e mensagem são obrigatórios' };
    }

    if (message.length > 4096) {
      return { success: false, error: 'Mensagem muito longa (máximo 4096 caracteres)' };
    }

    const phoneValidation = validatePhone(to);
    if (!phoneValidation.isValid) {
      return { success: false, error: phoneValidation.error };
    }

    // Check rate limit
    if (!checkRateLimit(establishmentId)) {
      return { 
        success: false, 
        error: 'Limite de mensagens atingido. Aguarde alguns minutos antes de tentar novamente.' 
      };
    }

    try {
      setIsSending(true);

      const result = await retryWithBackoff<WhatsAppHandlerResponse>(async () => {
        const { data, error } = await supabase.functions.invoke('whatsapp-unified-handler', {
          body: { 
            to: phoneValidation.formatted,
            message: message.trim(),
            establishmentId,
            messageType: 'custom'
          }
        });

        if (error) {
          throw new Error(error.message);
        }

        return data;
      });

      if (result?.success) {
        toast({
          title: "💬 Mensagem enviada!",
          description: `Mensagem WhatsApp enviada com sucesso para ${result.phoneNumber || phoneValidation.formatted}.`,
        });
        return { success: true, data: result };
      }

      return { success: false, error: result?.error || 'Falha ao enviar mensagem' };
    } catch (error) {
      console.error('Error sending custom message:', error);
      return { success: false, error: error instanceof Error ? error.message : 'Erro desconhecido' };
    } finally {
      setIsSending(false);
    }
  }, [validatePhone, checkRateLimit, retryWithBackoff]);

  // Testar conexão com WhatsApp Business API - CORRIGIDO para usar handler unificado
  const testWhatsAppConnection = useCallback(async (establishmentId: string): Promise<SendResult> => {
    if (!establishmentId) {
      return { success: false, error: 'ID do estabelecimento é obrigatório' };
    }

    try {
      setIsSending(true);

      // Get establishment config to validate setup
      const config = await getConfig(establishmentId);
      if (!config || !config.is_active) {
        return { 
          success: false, 
          error: 'WhatsApp não está configurado ou ativado para este estabelecimento' 
        };
      }

      if (!config.whatsapp_phone || !config.whatsapp_token) {
        return { 
          success: false, 
          error: 'Credenciais WhatsApp não configuradas' 
        };
      }

      // Send test message using unified handler
      const testMessage = `${i18n.t('common:whatsapp_test_header')}\n\n` +
        `${i18n.t('common:whatsapp_test_config_ok')}\n` +
        `${i18n.t('common:whatsapp_test_date', { date: new Date().toLocaleString() })}\n` +
        `${i18n.t('common:whatsapp_test_footer')}`;

      const result = await retryWithBackoff<WhatsAppHandlerResponse>(async () => {
        const { data, error } = await supabase.functions.invoke('whatsapp-unified-handler', {
          body: { 
            to: config.whatsapp_phone,
            message: testMessage,
            establishmentId,
            messageType: 'custom'
          }
        });

        if (error) {
          throw new Error(error.message);
        }

        return data;
      });

      if (result?.success) {
        toast({
          title: i18n.t('common:whatsapp_connection_tested_title'),
          description: i18n.t('common:whatsapp_connection_tested_desc'),
        });
        return { success: true, data: result };
      }

      return { success: false, error: result?.error || 'Teste de conexão falhou' };
    } catch (error) {
      console.error('Error testing WhatsApp connection:', error);
      const errorMessage = error instanceof Error ? error.message : i18n.t('common:whatsapp_test_error');
      
      toast({
        title: i18n.t('common:whatsapp_test_error_title'),
        description: errorMessage,
        variant: "destructive",
      });
      
      return { success: false, error: errorMessage };
    } finally {
      setIsSending(false);
    }
  }, [getConfig, retryWithBackoff]);

  // Clear cache manually if needed
  const clearCache = useCallback((establishmentId?: string) => {
    if (establishmentId) {
      configCache.current.delete(establishmentId);
    } else {
      configCache.current.clear();
    }
  }, []);

  // Get current rate limit status
  const getRateLimitStatus = useCallback((establishmentId?: string) => {
    const key = establishmentId || 'global';
    const current = rateLimitRef.current.get(key);
    const now = Date.now();

    if (!current || now > current.resetTime) {
      return { remaining: RATE_LIMIT, resetIn: 0 };
    }

    return { 
      remaining: Math.max(0, RATE_LIMIT - current.count), 
      resetIn: Math.max(0, current.resetTime - now) 
    };
  }, []);

  return {
    sendOrderToWhatsApp,
    sendStatusUpdateToCustomer,
    sendCustomMessage,
    testWhatsAppConnection,
    clearCache,
    getRateLimitStatus,
    isSending,
  };
}
